package com.clashofmusic.app

import com.clashofmusic.app.data.extractor.YouTubeAlbumMetadata
import org.junit.Assert.*
import org.junit.Test

class YouTubeAlbumMetadataTest {
    @Test fun explicitHtmlFieldDoesNotSwallowFollowingDescription() {
        assertEquals("狂言 & More", YouTubeAlbumMetadata.parse("Album: <b>狂言 &amp; More</b><br>CD/pre-order: https://example.org<br>Long promotional text"))
    }
    @Test fun marketingMentionsOfAnAlbumAreNotAlbumFields() {
        assertNull(YouTubeAlbumMetadata.parse("New album coming soon<br>『狂言 (Kyougen)』<br>CD/Pre-order/Pre-save: https://example.org"))
        assertNull(YouTubeAlbumMetadata.parse("Check the album: https://example.org"))
    }
    @Test fun autoGeneratedTopicLayoutFindsAlbumInsteadOfReleaseDate() {
        assertEquals("Actual Album", YouTubeAlbumMetadata.parse("Provided to YouTube by Label<br><br>Song · Artist<br><br>Actual Album<br>℗ 2024 Label<br>Released on: 2024-01-01<br>Auto-generated by YouTube."))
    }
    @Test fun releaseDateWithoutAlbumIsNeverUsedAsAlbum() {
        assertNull(YouTubeAlbumMetadata.parse("Released on: 2024-01-01\nAuto-generated by YouTube."))
    }
    @Test fun plainTextSpanishAndUnicodeEntitiesAreSupported() {
        assertEquals("Canción 日本語", YouTubeAlbumMetadata.parse("Álbum: Canci&#243;n 日本語\nOtra línea"))
    }
    @Test fun missingAndOverlongDescriptionsDoNotInventAnAlbum() {
        assertNull(YouTubeAlbumMetadata.parse(null)); assertNull(YouTubeAlbumMetadata.parse("Album: " + "x".repeat(181)))
    }
}
