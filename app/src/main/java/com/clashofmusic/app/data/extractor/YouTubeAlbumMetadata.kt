package com.clashofmusic.app.data.extractor

internal object YouTubeAlbumMetadata {
    fun parse(description: String?): String? {
        if (description.isNullOrBlank()) return null
        val separated = description.replace(Regex("(?i)<br\\s*/?>|</p>|</div>"), "\n")
        var text = separated.replace(Regex("(?is)<script[^>]*>.*?</script>|<style[^>]*>.*?</style>"), "")
            .replace(Regex("<[^>]+>"), "")
        linkedMapOf("&nbsp;" to " ", "&quot;" to "\"", "&#39;" to "'", "&apos;" to "'", "&lt;" to "<", "&gt;" to ">", "&amp;" to "&")
            .forEach { (entity, value) -> text = text.replace(entity, value) }
        text = Regex("&#(x[0-9a-fA-F]+|[0-9]+);").replace(text) { match ->
            val value = match.groupValues[1]
            val point = if (value.startsWith("x")) value.drop(1).toIntOrNull(16) else value.toIntOrNull()
            if (point != null && Character.isValidCodePoint(point)) String(Character.toChars(point)) else ""
        }
        val lines = text.lines().map { it.trim() }.filter { it.isNotEmpty() }
        fun valid(value: String) = value.length in 1..180 &&
            !value.contains(Regex("(?i)https?://|pre-order|pre-save|<[^>]+>")) &&
            !value.startsWith("℗") && !value.startsWith("©") && !value.startsWith("#")
        val field = Regex("(?iu)^(?:álbum|album)\\s*[:：]\\s*(.+)$")
        lines.forEach { line -> field.matchEntire(line)?.groupValues?.get(1)?.let { if (valid(it)) return it } }
        if (lines.any { it.startsWith("Provided to YouTube by ", true) } && lines.any { it.contains("Auto-generated by YouTube", true) }) {
            val credits = lines.indexOfFirst { it.contains(" · ") || it.contains(" • ") }
            val candidate = lines.getOrNull(credits + 1)
            if (credits >= 0 && candidate != null && valid(candidate) &&
                !candidate.contains(Regex("(?i)^(Released|Composer|Producer|Artist|Provided)"))) return candidate
        }
        return null
    }
}
